/**
 * Writes the icons the playground and the documentation site use, taken from
 * Lucide (`lucide-static`, pinned in `package.json`): every icon is drawn on
 * a 24-unit grid with a 2-unit round stroke and no fill, as the design system
 * asks. To use another icon, add its Lucide name to `ICONS` below and run
 * `npm run site:icons`.
 *
 * - `web/shared/icons.ts`: each icon's inner markup, and `icon()`, which wraps
 *   it in an `<svg class="icon">` (the playground's script, its page at build
 *   time, and the documentation's components).
 * - `web/shared/icons.css`: the icons drawn as CSS masks, `--icon-<name>`:
 *   the marks of external links and of lists that unfold (both sites), and
 *   the icons Starlight draws itself (the documentation).
 *
 * `--check` fails when either file is out of date.
 */
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
const LUCIDE = new URL("node_modules/lucide-static/", ROOT);
const MODULE = new URL("web/shared/icons.ts", ROOT);
const STYLESHEET = new URL("web/shared/icons.css", ROOT);

/** The icons in use, by Lucide name, with where they are used. */
const ICONS: Readonly<Record<string, string>> = {
  "arrow-left": "documentation: Previous",
  "arrow-right": "documentation: Next",
  "arrow-right-left": "playground: Swap",
  "book": "playground: Examples",
  "check": "playground: link copied",
  "chevron-down": "playground: buttons that unfold a list (mask)",
  "chevron-left": "playground: back to the options",
  "chevron-right": "documentation: sidebar groups, On this page (mask)",
  "copy": "playground: Copy, Copy code",
  "external-link": "links that open in a new tab (mask)",
  "link": "playground: Share",
  "menu": "documentation: phone menu (mask)",
  "pencil": "documentation: Edit page",
  "plus": "playground: add an option, a character, a spelling",
  "rotate-ccw": "playground: Reset",
  "search": "documentation: Search (mask)",
  "x": "playground: Clear, remove; documentation: close the menu (mask)",
};

/**
 * The icons drawn as CSS masks, with their stroke on the 24-unit grid: the
 * marks set at 0.75em beside a word take a heavier one, so that their line
 * stays near that of the text (about 1.3px at 16px) once scaled down.
 */
const MASKS: Readonly<Record<string, number>> = {
  "chevron-down": 2.5,
  "chevron-right": 2,
  "external-link": 2.5,
  "menu": 2,
  "search": 2,
  "x": 2,
};

const { version } = JSON.parse(
  await readFile(new URL("package.json", LUCIDE), "utf8"),
) as { version: string };

/** An icon's elements, one string, without the `<svg>` around them. */
async function inner(name: string): Promise<string> {
  const source = await readFile(new URL(`icons/${name}.svg`, LUCIDE), "utf8");
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(source)?.[1];
  if (body === undefined) throw new Error(`lucide-static: no ${name}.svg`);
  return body.trim().split(/\s*\n\s*/).join("").replace(/\s+\/>/g, "/>");
}

const markup = Object.fromEntries(
  await Promise.all(
    Object.keys(ICONS).map(async (name) => [name, await inner(name)]),
  ),
) as Record<string, string>;

const HEADER =
  `Generated by scripts/generate_icons.ts from lucide-static ${version}; do not edit.
SPDX-FileCopyrightText: Lucide Icons and Contributors; 2013-present Cole Bemis (Feather)
SPDX-License-Identifier: ISC AND MIT`;

function renderModule(): string {
  const entries = Object.keys(ICONS).map((name) =>
    `  // ${ICONS[name]}\n  "${name}":\n    '${markup[name]}',`
  );
  return `${HEADER.split("\n").map((line) => `// ${line}`).join("\n")}

/** Each icon's inner markup, on Lucide's 24-unit grid. */
export const ICONS = {
${entries.join("\n")}
} as const;

/** The name of an icon in use. */
export type IconName = keyof typeof ICONS;

/**
 * An icon as inline SVG, hidden from assistive technology: its size, stroke
 * and colour come from the \`.icon\` styles (2-unit round stroke, no fill,
 * the current colour). \`className\` adds classes; \`attributes\` is added
 * as is, after a space (\`hidden\`, say).
 */
export function icon(
  name: IconName,
  className = "",
  attributes = "",
): string {
  const classes = className ? \`icon \${className}\` : "icon";
  const more = attributes ? \` \${attributes}\` : "";
  return \`<svg class="\${classes}" viewBox="0 0 24 24" aria-hidden="true"\${more}>\${
    ICONS[name]
  }</svg>\`;
}
`;
}

/** An icon as a data URL, stroked in black: a mask takes its shape alone. */
function dataUrl(name: string): string {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="${
      MASKS[name]
    }" stroke-linecap="round" stroke-linejoin="round">${markup[name]}</svg>`;
  return `url("data:image/svg+xml,${
    svg.replace(/"/g, "'").replace(/[<>#%]/g, encodeURIComponent)
  }")`;
}

function renderStylesheet(): string {
  const lines = Object.keys(MASKS).map((name) =>
    `  --icon-${name}: ${dataUrl(name)};`
  );
  return `/*
${HEADER.split("\n").map((line) => ` * ${line}`).join("\n")}
 *
 * Icons as mask images: \`mask: var(--icon-search) center / contain no-repeat\`
 * over a \`currentColor\` background draws the icon in the text's colour.
 */
:root {
${lines.join("\n")}
}
`;
}

{
  // The module as the formatter leaves it, so that `--check` and
  // `dprint check` agree.
  const formatted = execFileSync(
    fileURLToPath(new URL("node_modules/.bin/dprint", ROOT)),
    ["fmt", "--stdin", fileURLToPath(MODULE)],
    { input: renderModule(), encoding: "utf8", cwd: fileURLToPath(ROOT) },
  );
  const outputs: [URL, string][] = [
    [MODULE, formatted],
    [STYLESHEET, renderStylesheet()],
  ];
  if (process.argv.includes("--check")) {
    for (const [file, expected] of outputs) {
      const current = await readFile(file, "utf8").catch(() => "");
      if (current !== expected) {
        console.error(
          `${
            file.pathname.slice(ROOT.pathname.length)
          } is out of date; run \`npm run site:icons\`.`,
        );
        process.exit(1);
      }
    }
  } else {
    for (const [file, content] of outputs) await writeFile(file, content);
  }
}
