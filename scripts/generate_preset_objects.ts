/**
 * Generates `src/prepared_presets.ts`, the `./presets` entry point: each
 * preset as prepared options, for the functions of the `./core` entry point.
 *
 * A preset is written as its changes to the defaults, which the module
 * applies when it is evaluated: the eight presets weigh less so than
 * resolved in full, and each export is annotated so that a bundle keeps only
 * the presets it imports. The module is formatted as `dprint` leaves it, so
 * that `--check` and `dprint check` agree.
 *
 * The module prepares the presets without resolving them, which would link
 * the steps that no preset takes (`src/steps.ts`): a preset that takes one
 * is refused, until the module links them too.
 *
 * Run with `npm run presets:generate`; `--check` fails if the module is
 * out of date.
 */
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {
  DEFAULT_CONVERSION_OPTIONS,
  listPresetMetadata,
  type PresetMetadata,
  resolveConversionOptions,
  type ResolvedConversionOptions,
} from "../src/mod.ts";
import { needsSteps } from "../src/steps.ts";

const ROOT = new URL("../", import.meta.url);
const MODULE = new URL("src/prepared_presets.ts", ROOT);
const GROUPS = [
  "transliteration",
  "greek",
  "betaCode",
  "text",
  "diacritics",
] as const satisfies readonly (keyof ResolvedConversionOptions)[];

/** The name of a preset's export: its identifier in camel case. */
function presetExportName(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, next: string) => next.toUpperCase());
}

function changesOf(id: PresetMetadata["id"]): string {
  const resolved = resolveConversionOptions({ preset: id });
  if (needsSteps(resolved)) {
    throw new Error(
      `The preset ${id} takes a step that src/steps.ts links when options ` +
        "are resolved: link the steps in src/prepared_presets.ts.",
    );
  }
  const groups: string[] = [];
  for (const group of GROUPS) {
    const defaults = DEFAULT_CONVERSION_OPTIONS[group] as Record<
      string,
      string
    >;
    const values = resolved[group] as Record<string, string>;
    const changed = Object.keys(values).filter((key) =>
      values[key] !== defaults[key]
    );
    if (changed.length === 0) continue;
    groups.push(
      `${group}: { ${
        changed.map((key) => `${key}: ${JSON.stringify(values[key])}`).join(
          ", ",
        )
      } }`,
    );
  }
  return `{ ${groups.join(", ")} }`;
}

/** A JSDoc comment holding `text`, wrapped at 80 columns. */
function comment(text: string): string {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(/\s+/)) {
    if (line !== "" && 3 + line.length + 1 + word.length > 80) {
      lines.push(line);
      line = word;
    } else {
      line = line === "" ? word : `${line} ${word}`;
    }
  }
  if (line !== "") lines.push(line);
  return ["/**", ...lines.map((text) => ` * ${text}`), " */"].join("\n");
}

function renderModule(): string {
  const presets = listPresetMetadata().map((preset) => `${
    comment(
      `\`${preset.id}\`, ${preset.name}, as prepared options: the options ` +
        `of \`{ preset: "${preset.id}" }\`. ${preset.description}`,
    )
  }
export const ${presetExportName(preset.id)}: PreparedOptions =
  /* @__PURE__ */ preset("${preset.id}", ${changesOf(preset.id)});
`);
  return `// Generated by scripts/generate_preset_objects.ts; do not edit.

/**
 * The presets as prepared options, for the functions of the \`./core\` entry
 * point: \`iso843Type2\` for \`{ preset: "iso-843-type-2" }\`, and so on.
 * A bundle keeps only the presets it imports, and neither the validation of
 * options nor the table of the presets. To change a preset's options,
 * prepare them with \`prepareOptions()\`, which takes the preset by name:
 * spreading a preset copies none of its options, and is refused.
 *
 * @example
 * \`\`\`ts
 * import { convert } from "@humanities/greek-conversion/core";
 * import { greekReader } from "@humanities/greek-conversion/greek";
 * import { sblGeneral } from "@humanities/greek-conversion/presets";
 * import { transliterationWriter } from "@humanities/greek-conversion/transliteration";
 *
 * convert("λόγος", greekReader, transliterationWriter, sblGeneral); // → logos
 * \`\`\`
 *
 * @module
 */

import { DEFAULT_CONVERSION_OPTIONS as DEFAULTS } from "./option_defaults.ts";
import type { Preset, ResolvedConversionOptions } from "./options.ts";
import { makePrepared, type PreparedOptions } from "./prepared.ts";

export type { PreparedOptions } from "./prepared.ts";

/** A preset's changes to the defaults. */
type Changes = {
  readonly [Group in keyof ResolvedConversionOptions]?: Partial<
    ResolvedConversionOptions[Group]
  >;
};

/** The defaults with the changes of the preset \`id\`, prepared. */
function preset(id: Preset, changes: Changes): PreparedOptions {
  const options: ResolvedConversionOptions = {
${
  GROUPS.map((group) =>
    `    ${group}: { ...DEFAULTS.${group}, ...changes.${group} },`
  ).join("\n")
}
  };
  return makePrepared(options, options, id);
}

${presets.join("\n")}`;
}

const formatted = execFileSync(
  fileURLToPath(new URL("node_modules/.bin/dprint", ROOT)),
  ["fmt", "--stdin", fileURLToPath(MODULE)],
  { input: renderModule(), encoding: "utf8", cwd: fileURLToPath(ROOT) },
);

if (process.argv.includes("--check")) {
  const current = await readFile(MODULE, "utf8").catch(() => "");
  if (current !== formatted) {
    console.error(
      "src/prepared_presets.ts is out of date; run `npm run presets:generate`.",
    );
    process.exit(1);
  }
} else {
  await writeFile(MODULE, formatted);
}
