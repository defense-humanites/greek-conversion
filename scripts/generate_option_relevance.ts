/**
 * Finds, for each conversion option and each pair of formats, whether some
 * value of the option changes the result, and writes the table the
 * playground uses to offer only the options that act on a conversion
 * (`web/option_relevance.ts`). `--check` fails when the table is out of
 * date.
 *
 * The probe texts gather, for each format, what the options act on: every
 * letter, mark, punctuation and context the options name, written in every
 * spelling the options give it, so that reading options meet the spellings
 * they read.
 */
import { readFile, writeFile } from "node:fs/promises";
import {
  CONVERSION_OPTION_VALUES,
  type ConversionOptions,
  convert,
  type Format,
  FORMATS,
} from "../src/mod.ts";

const TABLE = new URL("../web/option_relevance.ts", import.meta.url);

/** Greek that every option has something to act on. */
const GREEK = [
  "Ἕλλησιν ἐγένετο καὶ μέρει τινὶ τῶν βαρβάρων· τί λέγεις;",
  "ὑπὲρ ἀνθρώπων εὐθύς αὐτοῦ ηὑρέθη ὑϊός Ἀίδης ἀΐδιος ῥήτωρ ἄρρητος Πύρρος",
  "ἄγγελος ἀνάγκη σφίγξ ἔλεγχος ἐμπορία μπαμπάς ντομάτα ἀντί Μπαρ Ντίνος",
  "κἀγώ τοὔνομα ταὐτό ᾠδῇ τῷ θεῷ ᾄδω ᾱ̓́ ῐ ῡ ᾰ",
  "βίβλος ἐλπίσι ἐλπίδσι γέγραπται ψυχή ξένος φίλος χάρις",
  "ϲοφία Ϲωκράτης ϛʹ ϟʹ ϡʹ ϙ Ϙ ϝ ϳ αʹ ιβʹ ͵α",
  "ΛΟΓΟΣ λόγος Λόγος  δύο   διαστήματα πολυ-λογία πολυ‐λογία πολυ‿λογία",
  "πού πώς ή άνθρωπος",
].join("\n");

const values = CONVERSION_OPTION_VALUES as unknown as Record<
  string,
  Record<string, readonly string[]>
>;

function attempt(
  text: string,
  from: Format,
  to: Format,
  options: ConversionOptions,
): string | undefined {
  try {
    return convert(text, from, to, options);
  } catch {
    // Some values only combine with others.
    return undefined;
  }
}

function single(group: string, key: string, value: string): ConversionOptions {
  return { [group]: { [key]: value } } as ConversionOptions;
}

/** The probe text of a format: the Greek, written under every option. */
function probe(format: Format): string {
  if (format === "greek") return GREEK;
  const spellings = new Set([attempt(GREEK, "greek", format, {}) ?? ""]);
  for (const [group, table] of Object.entries(values)) {
    for (const [key, options] of Object.entries(table)) {
      for (const value of options) {
        const text = attempt(GREEK, "greek", format, single(group, key, value));
        if (text !== undefined) spellings.add(text);
      }
    }
  }
  return [...spellings].join("\n");
}

/** For each option, the format pairs where one of its values acts. */
function computeOptionRelevance(): Record<string, string[]> {
  const texts = Object.fromEntries(
    FORMATS.map((format) => [format, probe(format)]),
  ) as Record<Format, string>;
  const table: Record<string, string[]> = {};
  for (const [group, options] of Object.entries(values)) {
    for (const [key, choices] of Object.entries(options)) {
      const pairs: string[] = [];
      for (const from of FORMATS) {
        for (const to of FORMATS) {
          const plain = attempt(texts[from], from, to, {});
          const acts = choices.some((value) => {
            const result = attempt(
              texts[from],
              from,
              to,
              single(group, key, value),
            );
            return result !== undefined && result !== plain;
          });
          if (acts) pairs.push(`${from}>${to}`);
        }
      }
      table[`${group}.${key}`] = pairs;
    }
  }
  return table;
}

function render(table: Record<string, string[]>): string {
  // One pair per line, as the formatter leaves it.
  const lines = Object.entries(table).map(([option, pairs]) =>
    pairs.length
      ? `  "${option}": [\n${
        pairs.map((pair) => `    "${pair}",`).join("\n")
      }\n  ],`
      : `  "${option}": [],`
  );
  return `// Generated by scripts/generate_option_relevance.ts; do not edit.

/**
 * For each conversion option, the conversions ("from>to") on which one of
 * its values changes the result of the probe texts.
 */
export const OPTION_RELEVANCE: Readonly<Record<string, readonly string[]>> = {
${lines.join("\n")}
};
`;
}

{
  const expected = render(computeOptionRelevance());
  if (process.argv.includes("--print")) {
    console.log(expected);
  } else if (process.argv.includes("--check")) {
    const current = await readFile(TABLE, "utf8").catch(() => "");
    if (current !== expected) {
      console.error(
        "web/option_relevance.ts is out of date; run `npm run site:options`.",
      );
      process.exit(1);
    }
  } else {
    await writeFile(TABLE, expected);
  }
}
