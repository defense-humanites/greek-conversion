// Builds what the Python package takes from the library, from the working
// tree, after `npm ci`:
//
// - the bundle, `_bundle/greek_conversion.js`: the main entry point and the
//   bridge of `python/js/entry.ts`, as one IIFE script with no imports, which
//   any embedded engine can evaluate;
// - `_version.py`, the version of package.json in the spelling of PEP 440
//   (`1.0.0-rc.14` → `1.0.0rc14`), so that the two distributions share it,
//   followed by `.postN` when `PYTHON_POST_RELEASE` is N: a fix of the
//   Python package alone, published between two releases of the library;
// - `_options.py`, the types of the options (`option_types.ts`);
// - a copy of the LICENSE, which the wheel must carry from its own folder.
//
//   node python/scripts/build_bundle.mjs
//
// None of them is committed (`.gitignore`).

import { build } from "esbuild";
import { copyFile, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { optionTypes } from "./option_types.ts";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const { version } = JSON.parse(
  await readFile(here("../../package.json"), "utf8"),
);

/** The PEP 440 spelling of a semver version of this project. */
function pep440(semver) {
  const match = /^(\d+\.\d+\.\d+)(?:-(alpha|beta|rc)\.(\d+))?$/.exec(semver);
  if (match === null) throw new Error(`Unexpected version: ${semver}`);
  const [, release, stage, number] = match;
  if (stage === undefined) return release;
  return `${release}${{ alpha: "a", beta: "b", rc: "rc" }[stage]}${number}`;
}

await build({
  entryPoints: [here("../js/entry.ts")],
  outfile: here("../src/greek_conversion/_bundle/greek_conversion.js"),
  bundle: true,
  format: "iife",
  platform: "neutral",
  // ES2020, for the QuickJS of the archived `quickjs` package: the newer
  // syntax is lowered, and `_bundle/polyfills.js` supplies the few newer
  // built-ins the library uses where an engine lacks them.
  target: "es2020",
  minify: true,
  legalComments: "inline",
  define: { __VERSION__: JSON.stringify(version) },
  banner: {
    js:
      `/*! @humanities/greek-conversion ${version} | MIT | (C) Antoine Boquet */`,
  },
});

const post = process.env.PYTHON_POST_RELEASE ?? "";
if (!/^([1-9][0-9]*)?$/.test(post)) {
  throw new Error(`PYTHON_POST_RELEASE must be a positive integer: ${post}`);
}
const pythonVersion = pep440(version) + (post === "" ? "" : `.post${post}`);

await writeFile(
  here("../src/greek_conversion/_version.py"),
  `# Generated by python/scripts/build_bundle.mjs from package.json.\n` +
    `__version__ = "${pythonVersion}"\n` +
    `__js_version__ = "${version}"\n`,
);
await writeFile(here("../src/greek_conversion/_options.py"), optionTypes());
await copyFile(here("../../LICENSE"), here("../LICENSE"));

console.log(`Built the Python package's files for ${pythonVersion}.`);
