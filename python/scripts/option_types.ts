// The source of the Python package's `_options.py`: the types of the
// options (`TypedDict`, `Literal`), from the library's own table of options
// and values, so that type checkers, editors, and coding agents know every
// key, in snake_case, and every value. `build_bundle.mjs` writes it.

import {
  CONVERSION_OPTION_VALUES,
  FORMATS,
  listPresetMetadata,
} from "../../src/mod.ts";

/** `longVowels` → `long_vowels`, as the package writes the library's keys. */
const snake = (key: string) =>
  key.replace(/[A-Z]/g, (letter) => "_" + letter.toLowerCase());

/** `betaCode` → `BetaCode`, for the name of a class. */
const pascal = (key: string) => key[0].toUpperCase() + key.slice(1);

const literal = (values: readonly string[]) =>
  `Literal[${values.map((value) => JSON.stringify(value)).join(", ")}]`;

const quote = (text: string) => '"""' + text + '"""';

export function optionTypes(): string {
  const groups = Object.entries(CONVERSION_OPTION_VALUES).map(
    ([group, options]) => ({
      group,
      name: `${pascal(group)}Options`,
      fields: Object.entries(options as Record<string, readonly string[]>)
        .map(([key, values]) => `    ${snake(key)}: ${literal(values)}`),
    }),
  );
  const groupFields = groups.map(({ group, name }) =>
    `    ${snake(group)}: ${name}`
  );
  const presets = listPresetMetadata().map((metadata) => metadata.id);
  const forms = FORMATS.map((format) =>
    `${JSON.stringify(format)}: CustomCharacterForms`
  ).join(", ");
  return [
    quote(
      "The types of the options, generated by python/scripts/build_bundle.mjs\n" +
        "from the library's table of options and values: every key in\n" +
        "snake_case, every value as the library accepts it. Not committed.",
    ),
    "",
    "from __future__ import annotations",
    "",
    "from collections.abc import Sequence",
    "from typing import Literal, TypedDict",
    "",
    `Format = ${literal(FORMATS)}`,
    `Preset = ${literal(presets)}`,
    ...groups.flatMap(({ group, name, fields }) => [
      "",
      "",
      `class ${name}(TypedDict, total=False):`,
      `    ${quote(`The options of \`${snake(group)}\`.`)}`,
      "",
      ...fields,
    ]),
    "",
    "",
    "class SourceOptions(TypedDict, total=False):",
    `    ${
      quote("How the input is written, where it differs from the output.")
    }`,
    "",
    "    preset: Preset",
    ...groupFields,
    "",
    "",
    "class ConversionOptions(TypedDict, total=False):",
    `    ${
      quote("A preset, the groups of options that refine it, and `source`.")
    }`,
    "",
    "    preset: Preset",
    ...groupFields,
    "    source: SourceOptions",
    "",
    "",
    "class CharacterAlias(TypedDict, total=False):",
    `    ${quote("One more spelling of a built-in letter.")}`,
    "",
    "    letter: str",
    "    format: Format",
    "    spellings: Sequence[str]",
    "    uppercase: bool",
    "    override: bool",
    "",
    "",
    "class CustomCharacterForms(TypedDict, total=False):",
    "    lowercase: str",
    "    uppercase: str",
    "",
    "",
    `CustomCharacterFormsByFormat = TypedDict(`,
    `    "CustomCharacterFormsByFormat", {${forms}}`,
    ")",
    "",
    "",
    "class CustomCharacter(TypedDict, total=False):",
    `    ${quote("A character of a converter, with its form in each format.")}`,
    "",
    "    id: str",
    "    forms: CustomCharacterFormsByFormat",
    "    override: bool",
    "",
    "",
    "class ConverterConfiguration(TypedDict, total=False):",
    `    ${
      quote("The configuration of a converter: see `create_converter()`.")
    }`,
    "",
    "    preset: Preset",
    `    out_of_scope_behavior: Literal["preserve", "reject"]`,
    "    aliases: Sequence[CharacterAlias]",
    "    characters: Sequence[CustomCharacter]",
    "    repertoire: Sequence[str]",
    "    exclude: Sequence[str]",
    "",
  ].join("\n");
}
